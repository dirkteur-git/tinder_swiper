// Vondr PWA service worker — minimaal voor PoC
// Productie: vervang door next-pwa of workbox

const CACHE = "vondr-v1";
const SHELL = ["/", "/inbox"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(SHELL)).catch(() => {})
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;

  // Network-first voor HTML, cache-fallback bij offline
  if (req.headers.get("accept")?.includes("text/html")) {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
          return res;
        })
        .catch(() => caches.match(req).then((m) => m || caches.match("/inbox")))
    );
    return;
  }

  // Cache-first voor static assets
  event.respondWith(
    caches.match(req).then((m) => m || fetch(req))
  );
});
